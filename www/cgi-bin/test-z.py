#!/usr/bin/env python3
import sys
import os
import time

# Важно: сначала отправляем заголовки HTTP
print("Content-Type: text/plain")
print()  # Пустая строка между заголовками и телом

# Записываем много данных, которые не поместятся в буфер пайпа
# Буфер пайпа обычно 4-64 КБ (зависит от системы)
large_data = "X" * 1024 * 1024  # 1 МБ данных
sys.stdout.write(large_data)
sys.stdout.flush()  # Принудительно отправляем данные в буфер

# Теперь завершаем процесс, даже не дожидаясь,
# пока веб-сервер прочитает все данные
os._exit(0)  # Немедленное завершение без очистки
